'use client'

import { useMemo, useState } from 'react'
import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query'
import { Bell, CheckCheck, ArrowLeft, Trash2, Archive, Clock3, ExternalLink, RotateCcw } from 'lucide-react'
import { Button } from '@/components/ui/button'
import {
  AlertDialog,
  AlertDialogAction,
  AlertDialogCancel,
  AlertDialogContent,
  AlertDialogDescription,
  AlertDialogFooter,
  AlertDialogHeader,
  AlertDialogTitle,
} from '@/components/ui/alert-dialog'
import { apiGet, apiPost, apiDelete, apiPatch } from '@/lib/client'
import type { NotificationT } from '@/lib/client'
import { timeAgo } from '@/lib/format'
import { useAppStore } from '@/lib/store'
import { useSession } from '@/hooks/use-session'
import { ListingListSkeleton } from './skeletons'
import { EmptyState } from './empty-state'
import { ErrorState } from './listings-browse'
import { cn } from '@/lib/utils'
import { copy } from '@/lib/copy'

type InboxTab = 'new' | 'action' | 'scheduled' | 'completed' | 'archived'
type LifecycleAction = 'archive' | 'restore' | 'dismiss' | 'complete' | 'snooze'

const tabs: { id: InboxTab; label: string }[] = [
  { id: 'new', label: 'New' },
  { id: 'action', label: 'Action needed' },
  { id: 'scheduled', label: 'Scheduled' },
  { id: 'completed', label: 'Completed' },
  { id: 'archived', label: 'Archived' },
]

export function NotificationsView() {
  const { user, isLoading: sessionLoading } = useSession()
  const { navigate } = useAppStore()
  const queryClient = useQueryClient()
  const [confirmClear, setConfirmClear] = useState(false)
  const [tab, setTab] = useState<InboxTab>('new')
  const [snoozeFor, setSnoozeFor] = useState<string | null>(null)

  const { data, isLoading, isError, error, refetch } = useQuery({
    queryKey: ['notifications', 'list'],
    enabled: Boolean(user),
    queryFn: () => apiGet<{ notifications: NotificationT[]; unreadCount: number }>('/api/notifications'),
  })

  const invalidate = () => queryClient.invalidateQueries({ queryKey: ['notifications'] })
  const markRead = useMutation({
    mutationFn: (ids: string) => apiPost<{ ok: boolean }>(`/api/notifications/mark-read?ids=${ids}`),
    onSuccess: invalidate,
  })
  const lifecycle = useMutation({
    mutationFn: ({ id, action, minutes }: { id: string; action: LifecycleAction; minutes?: number }) =>
      apiPatch<{ ok: boolean }>(`/api/notifications/${encodeURIComponent(id)}/lifecycle`, { action, ...(minutes ? { minutes } : {}) }),
    onSuccess: () => {
      setSnoozeFor(null)
      void invalidate()
    },
  })
  const clearAll = useMutation({
    mutationFn: () => apiDelete<{ ok: boolean }>('/api/notifications?ids=all'),
    onSuccess: () => {
      setConfirmClear(false)
      void invalidate()
    },
  })

  const notifications = data?.notifications ?? []
  const visible = useMemo(() => {
    const now = Date.now()
    return notifications.filter((n) => {
      if (tab === 'archived') return Boolean(n.archivedAt)
      if (n.archivedAt || n.dismissedAt) return false
      if (tab === 'completed') return Boolean(n.completedAt)
      if (tab === 'scheduled') return Boolean(n.snoozedUntil && new Date(n.snoozedUntil).getTime() > now)
      if (n.completedAt || (n.snoozedUntil && new Date(n.snoozedUntil).getTime() > now)) return false
      if (tab === 'action') return Boolean(n.actionUrl)
      return !n.read
    })
  }, [notifications, tab])

  if (sessionLoading) return <ListingListSkeleton count={3} />
  if (!user) {
    return (
      <EmptyState
        title={copy.alerts.signInTitle}
        description={copy.alerts.signInSub}
        action={<Button onClick={() => useAppStore.getState().setAuthOpen(true)}>{copy.nav.signIn}</Button>}
      />
    )
  }
  if (isLoading) return <ListingListSkeleton count={3} />
  if (isError) return <ErrorState message={error instanceof Error ? error.message : 'Could not load notifications'} onRetry={() => refetch()} />

  function openAction(url: string) {
    // Destinations are generated by the server from a small internal allowlist.
    if (url === '/#/publish') navigate({ name: 'publish' })
    else if (url === '/#/account') navigate({ name: 'account' })
    else if (url === '/#/home') navigate({ name: 'home' })
    else if (url.startsWith('/#/shop/')) navigate({ name: 'shop', id: decodeURIComponent(url.slice('/#/shop/'.length)) })
    else if (url.startsWith('/#/edit/')) navigate({ name: 'edit', id: decodeURIComponent(url.slice('/#/edit/'.length)) })
    else navigate({ name: 'notifications' })
  }

  function openNotification(n: NotificationT) {
    if (!n.read) markRead.mutate(n.id)
    if (n.actionUrl) openAction(n.actionUrl)
    else if (n.listingId) navigate({ name: 'listing', id: n.listingId })
  }

  const unreadCount = data?.unreadCount ?? 0

  return (
    <div className="space-y-4">
      <div className="flex items-center justify-between gap-2">
        <div className="flex items-center gap-1">
          <Button variant="ghost" size="sm" className="-ml-2 gap-1 press lg:hidden" onClick={() => navigate({ name: 'browse' })}>
            <ArrowLeft className="size-4" aria-hidden /> Back
          </Button>
          <div>
            <h1 className="text-xl font-semibold tracking-tight">Your notifications</h1>
            <p className="text-xs text-muted-foreground">{unreadCount ? `${unreadCount} unread updates` : 'Your shop updates and reminders'}</p>
          </div>
        </div>
        <div className="flex shrink-0 items-center gap-1">
          {unreadCount > 0 ? (
            <Button size="sm" variant="outline" className="gap-1.5 press" onClick={() => markRead.mutate('all')} disabled={markRead.isPending}>
              <CheckCheck className="size-4" aria-hidden /> <span className="hidden sm:inline">Read all</span>
            </Button>
          ) : null}
          {notifications.length > 0 ? (
            <Button size="sm" variant="ghost" className="gap-1.5 px-2 text-muted-foreground hover:text-destructive press" aria-label="Clear all alerts" onClick={() => setConfirmClear(true)} disabled={clearAll.isPending}>
              <Trash2 className="size-4" aria-hidden /><span className="hidden sm:inline">Clear</span>
            </Button>
          ) : null}
        </div>
      </div>

      <div className="-mx-1 flex gap-1 overflow-x-auto px-1 pb-1" role="tablist" aria-label="Notification categories">
        {tabs.map((item) => (
          <button
            key={item.id}
            type="button"
            role="tab"
            aria-selected={tab === item.id}
            onClick={() => setTab(item.id)}
            className={cn(
              'shrink-0 rounded-full border px-3 py-1.5 text-xs font-medium transition-colors',
              tab === item.id ? 'border-primary bg-primary text-primary-foreground' : 'border-border bg-card text-muted-foreground hover:bg-accent',
            )}
          >
            {item.label}
          </button>
        ))}
      </div>

      {visible.length === 0 ? (
        <div className="rounded-xl border border-dashed bg-card px-5 py-12 text-center">
          <div className="mx-auto flex size-11 items-center justify-center rounded-full bg-accent text-primary"><Bell className="size-5" aria-hidden /></div>
          <p className="mt-3 text-sm font-semibold">{tab === 'new' ? copy.alerts.emptyTitle : `No ${tabs.find((item) => item.id === tab)?.label.toLowerCase()} notifications`}</p>
          <p className="mx-auto mt-1 max-w-sm text-xs leading-relaxed text-muted-foreground">{tab === 'new' ? copy.alerts.emptySub : 'Updates will appear here when they are available.'}</p>
        </div>
      ) : (
        <ul className="space-y-2">
          {visible.map((n, i) => (
            <li key={n.id} className="animate-in fade-in slide-in-from-bottom-2" style={{ animationDuration: '260ms', animationDelay: `${Math.min(i, 8) * 35}ms`, animationFillMode: 'both' }}>
              <article className={cn(
                'overflow-hidden rounded-xl border bg-card transition-colors',
                !n.read && 'border-l-[3px] border-l-primary',
                n.priority === 'HIGH' && 'shadow-sm',
              )}>
                <button type="button" onClick={() => openNotification(n)} className="w-full p-4 text-left hover:bg-accent/30">
                  <div className="flex items-start justify-between gap-3">
                    <div className="min-w-0">
                      <div className="mb-1 flex flex-wrap items-center gap-1.5">
                        {n.category === 'GROWTH' ? <span className="rounded-full bg-[#F5E8C8] px-2 py-0.5 text-[10px] font-semibold tracking-wide text-[#76541B]">GROWTH COACH</span> : null}
                        {n.priority === 'HIGH' ? <span className="rounded-full bg-primary/10 px-2 py-0.5 text-[10px] font-semibold text-primary">PRIORITY</span> : null}
                        {!n.read ? <span className="size-1.5 rounded-full bg-primary" aria-label="Unread" /> : null}
                      </div>
                      <h2 className="text-sm font-semibold leading-snug">{n.title}</h2>
                    </div>
                    <time className="shrink-0 pt-0.5 text-[11px] text-muted-foreground">{timeAgo(n.createdAt)}</time>
                  </div>
                  <p className="mt-1 text-sm leading-relaxed text-muted-foreground">{n.body}</p>
                  {n.actionLabel ? <span className="mt-3 inline-flex items-center gap-1 text-sm font-semibold text-primary">{n.actionLabel}<ExternalLink className="size-3.5" aria-hidden /></span> : null}
                  {n.snoozedUntil ? <p className="mt-2 text-xs text-muted-foreground">Reminder scheduled for {new Date(n.snoozedUntil).toLocaleString()}</p> : null}
                </button>

                <div className="flex flex-wrap items-center gap-1 border-t bg-muted/20 px-3 py-2">
                  {tab === 'archived' ? (
                    <Button size="sm" variant="ghost" className="h-8 gap-1.5 text-xs" onClick={() => lifecycle.mutate({ id: n.id, action: 'restore' })} disabled={lifecycle.isPending}>
                      <RotateCcw className="size-3.5" aria-hidden /> Restore
                    </Button>
                  ) : tab === 'completed' ? (
                    <span className="px-2 text-xs text-muted-foreground">Completed</span>
                  ) : (
                    <>
                      {n.actionUrl ? <Button size="sm" variant="outline" className="h-8 gap-1.5 text-xs" onClick={() => { if (!n.read) markRead.mutate(n.id); openAction(n.actionUrl!) }}><ExternalLink className="size-3.5" aria-hidden /> {n.actionLabel || 'Open action'}</Button> : null}
                      <div className="ml-auto flex flex-wrap items-center gap-1">
                        {snoozeFor === n.id ? (
                          <>
                            {[15, 30, 60, 1440].map((minutes) => (
                              <Button key={minutes} size="sm" variant="ghost" className="h-8 px-2 text-xs" onClick={() => lifecycle.mutate({ id: n.id, action: 'snooze', minutes })} disabled={lifecycle.isPending}>
                                {minutes === 1440 ? 'Tomorrow' : minutes === 60 ? '1 hour' : `${minutes} min`}
                              </Button>
                            ))}
                            <Button size="sm" variant="ghost" className="h-8 px-2 text-xs" onClick={() => setSnoozeFor(null)}>Cancel</Button>
                          </>
                        ) : (
                          <Button size="sm" variant="ghost" className="h-8 gap-1 px-2 text-xs text-muted-foreground" onClick={() => setSnoozeFor(n.id)}><Clock3 className="size-3.5" aria-hidden /> Remind me</Button>
                        )}
                        <Button size="sm" variant="ghost" className="h-8 gap-1 px-2 text-xs text-muted-foreground" onClick={() => lifecycle.mutate({ id: n.id, action: 'archive' })} disabled={lifecycle.isPending}><Archive className="size-3.5" aria-hidden /> Archive</Button>
                        <Button size="sm" variant="ghost" className="h-8 px-2 text-xs text-muted-foreground" onClick={() => lifecycle.mutate({ id: n.id, action: 'dismiss' })} disabled={lifecycle.isPending}>Dismiss</Button>
                      </div>
                    </>
                  )}
                </div>
              </article>
            </li>
          ))}
        </ul>
      )}

      <AlertDialog open={confirmClear} onOpenChange={setConfirmClear}>
        <AlertDialogContent>
          <AlertDialogHeader>
            <AlertDialogTitle>{copy.alerts.clearTitle}</AlertDialogTitle>
            <AlertDialogDescription>{copy.alerts.clearBody}</AlertDialogDescription>
          </AlertDialogHeader>
          <AlertDialogFooter>
            <AlertDialogCancel>Keep them</AlertDialogCancel>
            <AlertDialogAction className="bg-destructive text-white hover:bg-destructive/90" onClick={(e) => { e.preventDefault(); clearAll.mutate() }}>
              {clearAll.isPending ? copy.alerts.clearing : copy.alerts.clearGo}
            </AlertDialogAction>
          </AlertDialogFooter>
        </AlertDialogContent>
      </AlertDialog>
    </div>
  )
}
